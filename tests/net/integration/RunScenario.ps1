<#
.SYNOPSIS
    End-to-end test driver: starts vo_server with a temporary config and key pair on an ephemeral
    127.0.0.1 port, runs botclient scenario(s) against it and always stops the server again.
    Used by ctest (tests/CMakeLists.txt). Compatible with Windows PowerShell 5.1 and PowerShell 7.

.PARAMETER Scenario
    smoke | nokeys | genkeys | ping | login | chars | world | badstate | garbage | wrongkey | waitshutdown |
    speedhack | wallhack | floodmove | leaverace | dupworld | aoi | persist | load | noterrain
    With -Database additionally: restart (create character, stop server, start server, the character is
    still there); persist then means: walk, stay in the world until the server stops, start a new
    server, enter at the saved position.

.PARAMETER AssetsDir
    Compiled assets (assetc output) holding terrain/zone1/zone1.vterrain; written to world.assets_dir
    and passed to the bots as --terrain. Default: $env:VO_TEST_ASSET_DIR (set by ctest, which builds
    them in the assets.build fixture), else <RepoRoot>/assets.

.PARAMETER Database
    Run the server against PostgreSQL: its own schema vo_it_<time>_<random> in vedatonline_test
    (URL from VEDAT_TEST_DB_URL or db.test_connection_string in <RepoRoot>/config/server.local.toml),
    dropped again afterwards with vo_admin. Exits 77 (ctest: skipped) when no test database is
    configured or VEDAT_TEST_DB_URL=skip.

.EXAMPLE
    powershell -NoProfile -File tests\net\integration\RunScenario.ps1 -ServerExe build\x64-debug\bin\vo_server.exe `
        -BotExe build\x64-debug\bin\botclient.exe -Scenario ping -WorkDir $env:TEMP\vo_it_ping
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$ServerExe,
    [Parameter(Mandatory = $true)][string]$BotExe,
    [Parameter(Mandatory = $true)][string]$Scenario,
    [Parameter(Mandatory = $true)][string]$WorkDir,
    [string]$AdminExe = '',
    [string]$RepoRoot = '',
    [string]$AssetsDir = '',
    [switch]$Database
)

Set-StrictMode -Version 3.0
$ErrorActionPreference = 'Stop'

$script:Server = $null
$script:ServerOut = Join-Path $WorkDir 'server.out.log'
$script:ServerErr = Join-Path $WorkDir 'server.err.log'
$ConfigDir = Join-Path $WorkDir 'config'
$ConfigFile = Join-Path $ConfigDir 'server.toml'
$KeyDir = Join-Path $ConfigDir 'keys'
$PortFile = Join-Path $WorkDir 'port.txt'
$script:DbSchema = $null
$SkipExitCode = 77
if (-not $AssetsDir) { $AssetsDir = $env:VO_TEST_ASSET_DIR }
if (-not $AssetsDir -and $RepoRoot) { $AssetsDir = Join-Path $RepoRoot 'assets' }
$script:AssetsOverride = $null # noterrain: point the server at an empty directory
$TerrainFile = if ($AssetsDir) { Join-Path $AssetsDir 'terrain\zone1\zone1.vterrain' } else { '' }

function Write-Info([string]$Message) { Write-Host "[it:$Scenario] $Message" }

function Fail([string]$Message) { throw "FAIL: $Message" }

function Quote([string]$Arg) {
    if ($Arg -match '[\s"]') { return '"' + ($Arg -replace '"', '\"') + '"' }
    return $Arg
}

# Runs an executable to completion; returns @{ Code; Out } (stdout + stderr text).
function Invoke-Exe([string]$Exe, [string[]]$Arguments, [int]$TimeoutSec = 60) {
    $id = [guid]::NewGuid().ToString('N')
    $out = Join-Path $WorkDir "run_$id.out"
    $err = Join-Path $WorkDir "run_$id.err"
    $argLine = ($Arguments | ForEach-Object { Quote $_ }) -join ' '
    $p = Start-Process -FilePath $Exe -ArgumentList $argLine -NoNewWindow -PassThru `
        -RedirectStandardOutput $out -RedirectStandardError $err
    $null = $p.Handle # makes ExitCode available after exit (PowerShell quirk)
    if (-not $p.WaitForExit($TimeoutSec * 1000)) {
        Stop-Process -Id $p.Id -Force -ErrorAction SilentlyContinue
        Fail "$(Split-Path -Leaf $Exe) $argLine did not finish within $TimeoutSec s"
    }
    $p.WaitForExit()
    $text = ''
    foreach ($f in @($out, $err)) {
        if (Test-Path $f) { $text += [IO.File]::ReadAllText($f) }
    }
    $code = $p.ExitCode
    return @{ Code = $code; Out = $text }
}

function Write-Config([bool]$AutoRegister = $true) {
    New-Item -ItemType Directory -Force -Path $ConfigDir | Out-Null
    $auto = if ($AutoRegister) { 'true' } else { 'false' }
    # TOML literal string: no escapes, so Windows paths are fine.
    $assets = if ($script:AssetsOverride) { $script:AssetsOverride } else { $AssetsDir }
    $toml = @"
# Generated by tests/net/integration/RunScenario.ps1
[server]
name = "VedatOnline integration test"

[net]
listen_address = "127.0.0.1"
listen_port = 0
max_connections = 200

[world]
tick_rate = 20
assets_dir = '$assets'
stats_interval_s = 5

[log]
level = "debug"
file = ""

[auth]
dev_auto_register = $auto

[db]
connection_string = ""
"@
    if ($script:DbSchema) {
        # The connection string itself comes from VEDAT_DB_URL (set below), never from this file.
        $toml += "`nschema = `"$($script:DbSchema)`"`nrequired = true`npool_size = 2`n"
    }
    [IO.File]::WriteAllText($ConfigFile, $toml)
}

# Test database URL (never printed): VEDAT_TEST_DB_URL, else db.test_connection_string from the
# repository's config/server.local.toml. Returns $null if none (or VEDAT_TEST_DB_URL=skip).
function Get-LocalTomlValue([string]$Key) {
    if (-not $RepoRoot) { return $null }
    $local = Join-Path $RepoRoot 'config\server.local.toml'
    if (-not (Test-Path $local)) { return $null }
    $m = Select-String -Path $local -Pattern ('^\s*' + [regex]::Escape($Key) + '\s*=\s*"([^"]*)"') | Select-Object -First 1
    if ($null -eq $m) { return $null }
    return $m.Matches[0].Groups[1].Value
}

function Initialize-TestDb {
    $url = $env:VEDAT_TEST_DB_URL
    if ($url -eq 'skip') { return $false }
    if (-not $url) { $url = Get-LocalTomlValue 'test_connection_string' }
    if (-not $url) { return $false }
    if ($url -notmatch '(/vedatonline_test(\?|$))|(dbname\s*=\s*vedatonline_test(\s|$))') {
        Fail 'the test database URL must name database vedatonline_test'
    }
    if (-not $AdminExe -or -not (Test-Path $AdminExe)) { Fail '-Database needs -AdminExe (vo_admin) for the cleanup' }
    # Inherited by vo_server and vo_admin started from this script (and only by them).
    $env:VEDAT_DB_URL = $url
    $admin = Get-LocalTomlValue 'admin_connection_string'
    if ($admin) { $env:VEDAT_DB_ADMIN_URL = $admin } # lets the server create vedatonline_test if missing
    $unix = [int64]([DateTimeOffset]::UtcNow.ToUnixTimeSeconds())
    $script:DbSchema = 'vo_it_{0}_{1:x8}' -f $unix, (Get-Random -Maximum 2147483647)
    Write-Info "using schema $($script:DbSchema) in vedatonline_test"
    return $true
}

function Remove-TestDbSchema {
    if (-not $script:DbSchema) { return }
    try {
        $r = Invoke-Exe $AdminExe @('--config', $ConfigFile, 'testdb', 'drop-schema', $script:DbSchema) 60
        if ($r.Code -ne 0) { Write-Host "[it:$Scenario] warning: dropping $($script:DbSchema) failed: $($r.Out)" }
    }
    catch { Write-Host "[it:$Scenario] warning: dropping $($script:DbSchema) failed: $($_.Exception.Message)" }
}

function Get-AdminOutput([string[]]$Arguments) {
    $r = Invoke-Exe $AdminExe (@('--config', $ConfigFile) + $Arguments) 60
    Write-Host $r.Out.TrimEnd()
    if ($r.Code -ne 0) { Fail "vo_admin $($Arguments -join ' ') exited $($r.Code)" }
    return $r.Out
}

function New-Keys {
    $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--gen-keys')
    if ($r.Code -ne 0) { Fail "--gen-keys exited $($r.Code): $($r.Out)" }
    $pub = ([IO.File]::ReadAllText((Join-Path $KeyDir 'server_ed25519.pub'))).Trim()
    if ($pub -notmatch '^[0-9a-f]{64}$') { Fail "public key file malformed: '$pub'" }
    if ($r.Out -notmatch [regex]::Escape($pub)) { Fail '--gen-keys did not print the public key' }
    return $pub
}

function Start-Server([int]$RunSeconds = 120) {
    if (Test-Path $PortFile) { Remove-Item -Force $PortFile }
    # --run-seconds is a dead-man switch: the server stops by itself even if this script is killed.
    $argLine = "--config $(Quote $ConfigFile) --port 0 --port-file $(Quote $PortFile) --run-seconds $RunSeconds"
    $script:Server = Start-Process -FilePath $ServerExe -ArgumentList $argLine -NoNewWindow -PassThru `
        -RedirectStandardOutput $script:ServerOut -RedirectStandardError $script:ServerErr
    $null = $script:Server.Handle
    $deadline = (Get-Date).AddSeconds(20)
    while ((Get-Date) -lt $deadline) {
        if ($script:Server.HasExited) { Fail "server exited early with code $($script:Server.ExitCode)" }
        if (Test-Path $PortFile) {
            $text = ''
            try { $text = ([IO.File]::ReadAllText($PortFile)).Trim() } catch { $text = '' }
            if ($text -match '^\d+$' -and [int]$text -gt 0) {
                Write-Info "server pid $($script:Server.Id) listening on 127.0.0.1:$text"
                return [int]$text
            }
        }
        Start-Sleep -Milliseconds 50
    }
    Fail 'server did not report its port within 20 s'
}

function Stop-Server {
    if ($null -ne $script:Server -and -not $script:Server.HasExited) {
        Stop-Process -Id $script:Server.Id -Force -ErrorAction SilentlyContinue
        $script:Server.WaitForExit(10000) | Out-Null
    }
}

function Get-ServerLog {
    $text = ''
    foreach ($f in @($script:ServerOut, $script:ServerErr)) {
        if (Test-Path $f) {
            # Shared read: the server may still be running and writing the file.
            $fs = [IO.File]::Open($f, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::ReadWrite)
            try { $text += (New-Object IO.StreamReader($fs)).ReadToEnd() } finally { $fs.Dispose() }
        }
    }
    return $text
}

function Invoke-Bot([int]$Port, [string]$Key, [string]$BotScenario, [string[]]$Extra = @(), [int]$TimeoutSec = 150) {
    $botArgs = @('--host', '127.0.0.1', '--port', "$Port", '--server-key', $Key, '--scenario', $BotScenario)
    if ($TerrainFile) { $botArgs += @('--terrain', $TerrainFile) }
    $botArgs += $Extra
    $r = Invoke-Exe $BotExe $botArgs $TimeoutSec
    Write-Host $r.Out.TrimEnd()
    return $r
}

function Assert-Bot([int]$Port, [string]$Key, [string]$BotScenario, [string[]]$Extra = @(), [int]$TimeoutSec = 150) {
    $r = Invoke-Bot $Port $Key $BotScenario $Extra $TimeoutSec
    if ($r.Code -ne 0 -or $r.Out -notmatch "PASS scenario=$BotScenario") {
        Fail "botclient $BotScenario $($Extra -join ' ') exited $($r.Code)"
    }
}

$exitCode = 1
try {
    if (Test-Path $WorkDir) { Remove-Item -Recurse -Force $WorkDir }
    New-Item -ItemType Directory -Force -Path $WorkDir | Out-Null
    foreach ($exe in @($ServerExe, $BotExe)) { if (-not (Test-Path $exe)) { Fail "missing $exe" } }
    if ($Database) {
        if (-not (Initialize-TestDb)) {
            Write-Info 'SKIPPED: no test database (set VEDAT_TEST_DB_URL or db.test_connection_string in config/server.local.toml)'
            exit $SkipExitCode
        }
    }
    elseif ($Scenario -eq 'restart') {
        Fail 'scenario restart needs -Database'
    }
    Write-Config

    switch ($Scenario) {
        'restart' {
            # Create a character, stop the server (gracefully: --run-seconds), start a new server
            # process on the same schema and check that account and character are still there.
            $key = New-Keys
            $user = 'it_restart_' + (Get-Random -Maximum 99999)
            # (The world scenario walks for several seconds since M6: give the first server 30 s.)
            $port = Start-Server 30
            Assert-Bot $port $key 'world' @('--user', $user, '--password', 'restart-pass1')
            if (-not $script:Server.WaitForExit(60000)) { Fail 'first server did not stop after --run-seconds' }
            $script:Server.WaitForExit()
            if ($script:Server.ExitCode -ne 0) { Fail "first server exit code $($script:Server.ExitCode)" }
            $log = Get-ServerLog
            if ($log -notmatch 'using the PostgreSQL account service') { Fail 'first server did not use PostgreSQL' }
            if ($log -notmatch 'shutdown complete') { Fail "no 'shutdown complete' from the first server" }
            Write-Info 'first server stopped; starting a new server process (auto-registration off)'

            Write-Config -AutoRegister $false
            $port = Start-Server 120
            # The account exists only if it was persisted (auto-registration is off now).
            Assert-Bot $port $key 'login' @('--user', $user.ToUpperInvariant(), '--password', 'restart-pass1', '--expect', 'ok')
            Assert-Bot $port $key 'login' @('--user', $user, '--password', 'wrong-pass1', '--expect', 'invalid_credentials')
            # Two more characters fill the 3 slots only if the first one is still listed: then the
            # next create must fail with NoFreeSlot (CHAR_CREATE_RES result 3).
            Assert-Bot $port $key 'world' @('--user', $user, '--password', 'restart-pass1')
            Assert-Bot $port $key 'world' @('--user', $user, '--password', 'restart-pass1')
            $r = Invoke-Bot $port $key 'chars' @('--user', $user, '--password', 'restart-pass1')
            if ($r.Code -eq 0 -or $r.Out -notmatch 'CHAR_CREATE_RES result 3') {
                Fail 'after the restart the account should hold 3 characters (the one from before + 2 new)'
            }
            $list = Get-AdminOutput @('character', 'list', $user)
            if ($list -notmatch '3 character\(s\), 3 live') { Fail 'vo_admin does not list the 3 live characters' }
        }
        'persist' {
            $key = New-Keys
            $user = 'it_persist_' + (Get-Random -Maximum 99999)
            $state = Join-Path $WorkDir 'persist_state.txt'
            if (-not $Database) {
                # Walk, LOGOUT, log in again on the same server: entered at the saved position.
                $port = Start-Server
                Assert-Bot $port $key 'persist' @('--user', $user, '--password', 'persist-pass1', '--state-file', $state)
            }
            else {
                # Walk and stay in the world; the server stops by itself (--run-seconds) and must save
                # the position on the way out. A new server process then puts the character there.
                $port = Start-Server 25
                Assert-Bot $port $key 'persist' @('--user', $user, '--password', 'persist-pass1', '--phase', 'stay',
                    '--state-file', $state, '--timeout-ms', '20000')
                if (-not $script:Server.WaitForExit(60000)) { Fail 'first server did not stop after --run-seconds' }
                $script:Server.WaitForExit()
                if ($script:Server.ExitCode -ne 0) { Fail "first server exit code $($script:Server.ExitCode)" }
                $log = Get-ServerLog
                if ($log -notmatch 'using the PostgreSQL account service') { Fail 'first server did not use PostgreSQL' }
                if ($log -notmatch 'shutdown complete') { Fail "no 'shutdown complete' from the first server" }
                Write-Info "first server stopped; expected position: $(([IO.File]::ReadAllText($state)).Trim())"
                Write-Config -AutoRegister $false
                $port = Start-Server 120
                Assert-Bot $port $key 'persist' @('--user', $user, '--password', 'persist-pass1', '--phase', 'check',
                    '--state-file', $state)
            }
        }
        'items' {
            # Starter kit, equip/unequip, ENTITY_EQUIP and re-entry (docs/PROTOCOL_ITEMS.md). With
            # -Database also vo_admin list-items / give-item and a second entry that sees the item.
            $key = New-Keys
            $port = Start-Server
            $user = 'it_items_' + (Get-Random -Maximum 99999)
            $state = Join-Path $WorkDir 'items_state.txt'
            Assert-Bot $port $key 'items' @('--user', $user, '--password', 'items-pass1', '--state-file', $state)
            if ($Database) {
                $name = ([IO.File]::ReadAllText($state)).Trim()
                $list = Get-AdminOutput @('list-items', $name)
                if ($list -notmatch 'starter kit granted' -or $list -notmatch '3 item\(s\)') {
                    Fail 'vo_admin list-items does not show the granted kit'
                }
                $given = Get-AdminOutput @('give-item', $name, '7')
                if ($given -notmatch 'in bag/0') { Fail 'vo_admin give-item did not use the lowest free bag slot' }
                Assert-Bot $port $key 'items' @('--user', $user, '--password', 'items-pass1', '--phase', 'check',
                    '--state-file', $state)
                $r = Invoke-Exe $AdminExe @('--config', $ConfigFile, 'give-item', $name, '999') 60
                if ($r.Code -ne 3) { Fail "give-item with an unknown template: exit $($r.Code) (expected 3)" }
            }
        }
        'combat' {
            # Combat (docs/PROTOCOL_COMBAT.md): a warrior kills a Kül Çömezi (COMBAT_EVENT / ENTITY_DEATH /
            # XP_GAIN consistency, its skill), dies to the Kor Bekçisi and respawns. With -Database also
            # vo_admin set-level (clamped to the cap) and an entry at that level with full hp/mp.
            $key = New-Keys
            $port = Start-Server 170
            $user = 'it_combat_' + (Get-Random -Maximum 99999)
            $state = Join-Path $WorkDir 'combat_state.txt'
            Assert-Bot $port $key 'combat' @('--user', $user, '--password', 'combat-pass1', '--state-file', $state,
                '--timeout-ms', '20000') 170
            $log = Get-ServerLog
            if ($log -notmatch 'monsters: \d+ template\(s\), \d+ spawn point\(s\)') { Fail 'the server did not load gamedata/monsters.toml' }
            if ($Database) {
                $name = ([IO.File]::ReadAllText($state)).Trim()
                $out = Get-AdminOutput @('set-level', $name, '99')
                if ($out -notmatch 'is now level 10') { Fail "vo_admin set-level did not clamp to level 10: $out" }
                Assert-Bot $port $key 'combat' @('--user', $user, '--password', 'combat-pass1', '--phase', 'check',
                    '--state-file', $state)
                $r = Invoke-Exe $AdminExe @('--config', $ConfigFile, 'set-level', 'Yokbuisim', '3') 60
                if ($r.Code -ne 3) { Fail "set-level of an unknown character: exit $($r.Code) (expected 3)" }
            }
        }
        'load' {
            # A small load run: every bot must get in, wander without a single correction and stay
            # connected.
            $key = New-Keys
            $port = Start-Server 120
            Assert-Bot $port $key 'load' @('--bots', '24', '--duration', '8', '--threads', '2', '--ramp-ms', '20') 170
            $log = Get-ServerLog
            if ($log -notmatch 'world: \d+ s: \d+ players') { Fail 'no periodic world statistics in the server log' }
        }
        'noterrain' {
            # Missing and corrupt terrain: the server refuses to start with exit code 6 and says why.
            $null = New-Keys
            $script:AssetsOverride = Join-Path $WorkDir 'no_assets'
            New-Item -ItemType Directory -Force -Path $script:AssetsOverride | Out-Null
            Write-Config
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--port', '0', '--run-seconds', '1') 30
            Write-Host $r.Out.TrimEnd()
            if ($r.Code -ne 6) { Fail "expected exit code 6 without terrain, got $($r.Code)" }
            if ($r.Out -notmatch 'cannot load zone 1' -or $r.Out -notmatch 'assetc build') { Fail 'missing-terrain message not clear' }
            $bad = Join-Path $script:AssetsOverride 'terrain\zone1'
            New-Item -ItemType Directory -Force -Path $bad | Out-Null
            [IO.File]::WriteAllBytes((Join-Path $bad 'zone1.vterrain'), [byte[]](1..64))
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--port', '0', '--run-seconds', '1') 30
            Write-Host $r.Out.TrimEnd()
            if ($r.Code -ne 6) { Fail "expected exit code 6 with a corrupt terrain, got $($r.Code)" }
            if ($r.Out -notmatch 'cannot load zone 1') { Fail 'corrupt-terrain message not clear' }
        }
        'smoke' {
            $null = New-Keys
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--port', '0', '--run-seconds', '1') 30
            Write-Host $r.Out.TrimEnd()
            if ($r.Code -ne 0) { Fail "server exited with $($r.Code)" }
            if ($r.Out -notmatch 'shutdown complete') { Fail "no 'shutdown complete' in the output" }
        }
        'nokeys' {
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--port', '0', '--run-seconds', '1') 30
            Write-Host $r.Out.TrimEnd()
            if ($r.Code -ne 2) { Fail "expected exit code 2 without keys, got $($r.Code)" }
            if ($r.Out -notmatch 'server key not available' -or $r.Out -notmatch '--gen-keys') {
                Fail 'missing-key message not clear'
            }
        }
        'genkeys' {
            $first = New-Keys
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--gen-keys')
            if ($r.Code -eq 0) { Fail '--gen-keys overwrote existing keys without --force' }
            if ($r.Out -notmatch 'already exist') { Fail "refusal message missing: $($r.Out)" }
            $after = ([IO.File]::ReadAllText((Join-Path $KeyDir 'server_ed25519.pub'))).Trim()
            if ($after -ne $first) { Fail 'key file changed although overwrite was refused' }
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--gen-keys', '--force')
            if ($r.Code -ne 0) { Fail "--gen-keys --force exited $($r.Code)" }
            $forced = ([IO.File]::ReadAllText((Join-Path $KeyDir 'server_ed25519.pub'))).Trim()
            if ($forced -eq $first) { Fail '--force did not create a new key' }
        }
        'login' {
            $key = New-Keys
            $port = Start-Server
            $user = 'it_user_' + (Get-Random -Maximum 99999)
            Assert-Bot $port $key 'login' @('--user', $user, '--password', 'correct-horse', '--expect', 'ok')
            Assert-Bot $port $key 'login' @('--user', $user.ToUpperInvariant(), '--password', 'correct-horse', '--expect', 'ok')
            # 5 failures per IP per minute are answered normally, the 6th attempt is rate limited.
            for ($i = 1; $i -le 5; $i++) {
                Assert-Bot $port $key 'login' @('--user', $user, '--password', 'wrong-password', '--expect', 'invalid_credentials')
            }
            Assert-Bot $port $key 'login' @('--user', $user, '--password', 'correct-horse', '--expect', 'too_many_attempts')
        }
        'waitshutdown' {
            $key = New-Keys
            $port = Start-Server 4
            Assert-Bot $port $key 'waitshutdown' @('--timeout-ms', '20000')
            if (-not $script:Server.WaitForExit(20000)) { Fail 'server did not exit after --run-seconds' }
            $script:Server.WaitForExit()
            if ($script:Server.ExitCode -ne 0) { Fail "server exit code $($script:Server.ExitCode)" }
            if ((Get-ServerLog) -notmatch 'shutdown complete') { Fail "no 'shutdown complete' in the server log" }
        }
        { $_ -in @('ping', 'chars', 'world', 'badstate', 'garbage', 'wrongkey', 'speedhack', 'wallhack', 'floodmove', 'leaverace', 'dupworld', 'aoi') } {
            $key = New-Keys
            $port = Start-Server
            Assert-Bot $port $key $Scenario
            if ($Scenario -eq 'world') {
                # Both races start at their own spawn point.
                Assert-Bot $port $key 'world' @('--race', '2')
            }
            if ($Scenario -in @('garbage', 'badstate', 'floodmove', 'leaverace')) {
                # The server must survive the bad client and keep serving others.
                Assert-Bot $port $key 'ping' @('--count', '1')
            }
        }
        default { Fail "unknown scenario '$Scenario'" }
    }
    Write-Info 'PASS'
    $exitCode = 0
}
catch {
    Write-Host "[it:$Scenario] $($_.Exception.Message)" -ForegroundColor Red
    $log = Get-ServerLog
    if ($log) { Write-Host "---- server output ----`n$log" }
    $exitCode = 1
}
finally {
    Stop-Server
    Remove-TestDbSchema
}
exit $exitCode

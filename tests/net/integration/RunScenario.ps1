                $loadArgs = @('--bots', '24', '--duration', '40', '--threads', '2', '--ramp-ms', '20', '--zones')
            }
            Assert-Bot $port $key 'load' $loadArgs 170
            $log = Get-ServerLog
            if ($log -notmatch 'world: \d+ s: \d+ players') { Fail 'no periodic world statistics in the server log' }
        }
        'noterrain' {
            # Missing and corrupt terrain: the server refuses to start with exit code 6 and says why.
            $null = New-Keys
            $script:AssetsOverride = Join-Path $WorkDir 'no_assets'
            New-Item -ItemType Directory -Force -Path $script:AssetsOverride | Out-Null
            Write-Config
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--port', '0', '--run-seconds', '1') 30
            Write-Host $r.Out.TrimEnd()
            if ($r.Code -ne 6) { Fail "expected exit code 6 without terrain, got $($r.Code)" }
            if ($r.Out -notmatch 'cannot load zone 1' -or $r.Out -notmatch 'assetc build') { Fail 'missing-terrain message not clear' }
            $bad = Join-Path $script:AssetsOverride 'terrain\zone1'
            New-Item -ItemType Directory -Force -Path $bad | Out-Null
            [IO.File]::WriteAllBytes((Join-Path $bad 'zone1.vterrain'), [byte[]](1..64))
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--port', '0', '--run-seconds', '1') 30
            Write-Host $r.Out.TrimEnd()
            if ($r.Code -ne 6) { Fail "expected exit code 6 with a corrupt terrain, got $($r.Code)" }
            if ($r.Out -notmatch 'cannot load zone 1') { Fail 'corrupt-terrain message not clear' }
        }
        'smoke' {
            $null = New-Keys
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--port', '0', '--run-seconds', '1') 30
            Write-Host $r.Out.TrimEnd()
            if ($r.Code -ne 0) { Fail "server exited with $($r.Code)" }
            if ($r.Out -notmatch 'shutdown complete') { Fail "no 'shutdown complete' in the output" }
        }
        'nokeys' {
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--port', '0', '--run-seconds', '1') 30
            Write-Host $r.Out.TrimEnd()
            if ($r.Code -ne 2) { Fail "expected exit code 2 without keys, got $($r.Code)" }
            if ($r.Out -notmatch 'server key not available' -or $r.Out -notmatch '--gen-keys') {
                Fail 'missing-key message not clear'
            }
        }
        'genkeys' {
            $first = New-Keys
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--gen-keys')
            if ($r.Code -eq 0) { Fail '--gen-keys overwrote existing keys without --force' }
            if ($r.Out -notmatch 'already exist') { Fail "refusal message missing: $($r.Out)" }
            $after = ([IO.File]::ReadAllText((Join-Path $KeyDir 'server_ed25519.pub'))).Trim()
            if ($after -ne $first) { Fail 'key file changed although overwrite was refused' }
            $r = Invoke-Exe $ServerExe @('--config', $ConfigFile, '--gen-keys', '--force')
            if ($r.Code -ne 0) { Fail "--gen-keys --force exited $($r.Code)" }
            $forced = ([IO.File]::ReadAllText((Join-Path $KeyDir 'server_ed25519.pub'))).Trim()
            if ($forced -eq $first) { Fail '--force did not create a new key' }
        }
        'login' {
            $key = New-Keys
            $port = Start-Server
            $user = 'it_user_' + (Get-Random -Maximum 99999)
            Assert-Bot $port $key 'login' @('--user', $user, '--password', 'correct-horse', '--expect', 'ok')
            Assert-Bot $port $key 'login' @('--user', $user.ToUpperInvariant(), '--password', 'correct-horse', '--expect', 'ok')
            # 5 failures per IP per minute are answered normally, the 6th attempt is rate limited.
            for ($i = 1; $i -le 5; $i++) {
                Assert-Bot $port $key 'login' @('--user', $user, '--password', 'wrong-password', '--expect', 'invalid_credentials')
            }
            Assert-Bot $port $key 'login' @('--user', $user, '--password', 'correct-horse', '--expect', 'too_many_attempts')
        }
        'waitshutdown' {
            $key = New-Keys
            $port = Start-Server 4
            Assert-Bot $port $key 'waitshutdown' @('--timeout-ms', '20000')
            if (-not $script:Server.WaitForExit(20000)) { Fail 'server did not exit after --run-seconds' }
            $script:Server.WaitForExit()
            if ($script:Server.ExitCode -ne 0) { Fail "server exit code $($script:Server.ExitCode)" }
            if ((Get-ServerLog) -notmatch 'shutdown complete') { Fail "no 'shutdown complete' in the server log" }
        }
        { $_ -in @('ping', 'chars', 'world', 'badstate', 'garbage', 'wrongkey', 'speedhack', 'wallhack', 'floodmove', 'leaverace', 'dupworld', 'aoi') } {
            $key = New-Keys
            $port = Start-Server
            Assert-Bot $port $key $Scenario
            if ($Scenario -eq 'world') {
                # Both races start at their own spawn point.
                Assert-Bot $port $key 'world' @('--race', '2')
            }
            if ($Scenario -in @('garbage', 'badstate', 'floodmove', 'leaverace')) {
                # The server must survive the bad client and keep serving others.
                Assert-Bot $port $key 'ping' @('--count', '1')
            }
        }
        default { Fail "unknown scenario '$Scenario'" }
    }
    Write-Info 'PASS'
    $exitCode = 0
}
catch {
    Write-Host "[it:$Scenario] $($_.Exception.Message)" -ForegroundColor Red
    $log = Get-ServerLog
    if ($log) { Write-Host "---- server output ----`n$log" }
    $exitCode = 1
}
finally {
    Stop-Server
    Remove-TestDbSchema
}
exit $exitCode
